export function listSchematicsSummary() {
  return Object.values(BOARD_SCHEMATICS).map((s) => ({
    id: s.id,
    title: s.title,
    architecture: s.architecture,
    components_count: s.components.length,
    pins_count: s.pins.length,
  }));
}

export function getSchematicDetail(schematicId: string): BoardSchematic | null {
  return BOARD_SCHEMATICS[schematicId] || null;
}

export function getSchematicForDevice(device?: ConnectedDevice): BoardSchematic {
  if (!device) return BOARD_SCHEMATICS.samsung_a325f_board;
  const brand = (device.brand || '').toLowerCase();
  const chipset = (device.chipset || '').toLowerCase();
  const chipsetName = (device.chipsetName || '').toLowerCase();
  const socId = (device.socId || '').toLowerCase();
  const model = (device.model || '').toLowerCase();
  const market = (device.marketName || '').toLowerCase();

  if (brand.includes('apple') || brand.includes('iphone') || chipset.includes('apple')) {
    if (model.includes('15') || market.includes('15') || socId.includes('8130') || chipsetName.includes('a17')) {
      return BOARD_SCHEMATICS.iphone_15_pro_max_a17;
    }
    return BOARD_SCHEMATICS.iphone_14_pro_board;
  }
  if (brand.includes('google') || chipset.includes('tensor') || market.includes('pixel')) {
    return BOARD_SCHEMATICS.google_pixel_tensor_g3;
  }
  if (chipset.includes('unisoc') || model.includes('c53') || model.includes('rmx3760') || chipsetName.includes('tiger')) {
    return BOARD_SCHEMATICS.unisoc_tiger_board;
  }
  if (chipset.includes('kirin') || brand.includes('huawei') || brand.includes('honor')) {
    return BOARD_SCHEMATICS.huawei_kirin_board;
  }
  if (chipset.includes('exynos') || model.includes('a54') || model.includes('a55')) {
    return BOARD_SCHEMATICS.samsung_exynos_a54_board;
  }
  if (
    model.includes('s928') ||
    (brand.includes('samsung') && chipset.includes('qualcomm') && (market.includes('s24 ultra') || socId.includes('sm8650')))
  ) {
    return BOARD_SCHEMATICS.samsung_s24_ultra_sm8650;
  }
  if (model.includes('xiaomi 14') || market.includes('xiaomi 14') || (brand.includes('xiaomi') && socId.includes('sm8650'))) {
    return BOARD_SCHEMATICS.xiaomi_14_hyperos_qcom;
  }
  if (
    brand.includes('oppo') ||
    brand.includes('realme') ||
    brand.includes('oneplus') ||
    chipsetName.includes('dimensity') ||
    socId.includes('mt68') ||
    socId.includes('mt69')
  ) {
    return BOARD_SCHEMATICS.oppo_realme_dimensity_board;
  }
  if (
    brand.includes('infinix') ||
    brand.includes('tecno') ||
    chipsetName.includes('helio') ||
    socId.includes('mt6789')
  ) {
    return BOARD_SCHEMATICS.infinix_tecno_helio_board;
  }
  if (chipset.includes('qualcomm') || model.includes('poco') || brand.includes('xiaomi')) {
    return BOARD_SCHEMATICS.xiaomi_qualcomm_mtk_board;
  }
  return BOARD_SCHEMATICS.samsung_a325f_board;
}
